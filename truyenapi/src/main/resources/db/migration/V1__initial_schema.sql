CREATE TABLE authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE stories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    cover_url VARCHAR(500),
    summary TEXT,
    status VARCHAR(20) NOT NULL,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_stories_author
        FOREIGN KEY (author_id) REFERENCES authors (id)
);

CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_password_reset_tokens_token UNIQUE (token),
    CONSTRAINT fk_password_reset_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id BIGINT NOT NULL,
    chapter_no INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_chapters_story_id_chapter_no UNIQUE (story_id, chapter_no),
    CONSTRAINT fk_chapters_story
        FOREIGN KEY (story_id) REFERENCES stories (id)
);

CREATE TABLE story_categories (
    story_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT pk_story_categories PRIMARY KEY (story_id, category_id),
    CONSTRAINT fk_story_categories_story
        FOREIGN KEY (story_id) REFERENCES stories (id),
    CONSTRAINT fk_story_categories_category
        FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE library (
    user_id BIGINT NOT NULL,
    story_id BIGINT NOT NULL,
    added_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_library PRIMARY KEY (user_id, story_id),
    CONSTRAINT fk_library_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_library_story
        FOREIGN KEY (story_id) REFERENCES stories (id)
);

CREATE TABLE reading_history (
    user_id BIGINT NOT NULL,
    story_id BIGINT NOT NULL,
    chapter_id BIGINT,
    char_offset INTEGER,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_reading_history PRIMARY KEY (user_id, story_id),
    CONSTRAINT fk_reading_history_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reading_history_story
        FOREIGN KEY (story_id) REFERENCES stories (id),
    CONSTRAINT fk_reading_history_chapter
        FOREIGN KEY (chapter_id) REFERENCES chapters (id)
);

CREATE TABLE bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    chapter_id BIGINT NOT NULL,
    char_offset INTEGER,
    note VARCHAR(500),
    CONSTRAINT fk_bookmarks_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_bookmarks_chapter
        FOREIGN KEY (chapter_id) REFERENCES chapters (id)
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    story_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_comments_story
        FOREIGN KEY (story_id) REFERENCES stories (id)
);

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    story_id BIGINT NOT NULL,
    stars SMALLINT NOT NULL,
    CONSTRAINT uk_ratings_user_id_story_id UNIQUE (user_id, story_id),
    CONSTRAINT ck_ratings_stars_range CHECK (stars BETWEEN 1 AND 5),
    CONSTRAINT fk_ratings_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ratings_story
        FOREIGN KEY (story_id) REFERENCES stories (id)
);
